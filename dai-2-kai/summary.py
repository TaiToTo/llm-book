"""まとめ — 効率化の使い分け"""

from util import part


def summary():
    part(9, "まとめ — 効率化の使い分け")
    print("""
  ┌────────────────────────┬──────────────────┬───────────────────┐
  │ 処理                   │ ボトルネック     │ 効率化の方法      │
  ├────────────────────────┼──────────────────┼───────────────────┤
  │ LLM API呼び出し        │ 通信待ち (I/O)   │ asyncio           │
  │ ローカル推論 (HF)      │ CPU/GPU 計算     │ バッチ化          │
  │ ローカル埋め込み生成   │ CPU/GPU 計算     │ バッチ化          │
  │ CPU前処理 (tokenize等) │ CPU 計算         │ multiprocessing   │
  │ ファイル書き出し       │ ディスク I/O     │ 非同期化・分離    │
  │ 大量API一括処理        │ 通信 + コスト    │ バッチAPI         │
  └────────────────────────┴──────────────────┴───────────────────┘

  ■ 今日のデモで確認したこと:

    1. ローカル推論・埋め込みは「バッチ化」で大幅に高速化できた
       → GPU/CPUの並列計算能力はバッチで活きる

    2. API呼び出しは「asyncio」で待ち時間を重ね合わせて高速化できた
       → 通信待ちの間に次のリクエストを投げる

    3. バッチAPIはリアルタイム性を捨てる代わりにコストと負荷を下げる
       → 大量データの一括処理に向く

  ■ 持ち帰ってほしいこと:

    1. 速くする方法は1つではない
    2. 遅さの原因によって効率化の方法は変わる
    3. API・ローカル推論・保存を同じ感覚で扱わない
""")


if __name__ == "__main__":
    summary()
