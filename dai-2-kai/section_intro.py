def section_4_concepts():
    section(4, "必要最小限の概念整理")
    print("""
  ■ I/Oバウンド vs CPUバウンド

    I/Oバウンド : 処理自体は軽いが、外部の応答を「待つ」時間が長い
                  → API呼び出し、ファイル読み書き、DB問い合わせ
    CPUバウンド : 計算そのものに時間がかかる
                  → モデル推論、行列演算、前処理

  ■ asyncio — I/Oバウンドに効く

    「待ち時間」を重ね合わせる。1つの応答を待つ間に次のリクエストを投げる。
    → API呼び出しに最適

  ■ バッチ化 — CPUバウンド (GPU推論) に効く

    複数の入力をまとめて1回の推論に渡す。
    → GPU並列性を活かせる。ローカル推論・埋め込みに最適

  ■ multiprocessing — CPUバウンドに効く

    複数のCPUコアで並列処理する。
    → CPU前処理が重い場合に検討
""")


